export function findClubByName(clubName: string): ClubInfo | undefined {
  const normalized = clubName.toLowerCase().trim();
  if (normalized.includes('barcelona')) return CLUBS.FCB;
  if (normalized.includes('paris saint-germain') || normalized === 'psg') return CLUBS.PSG;
  if (normalized.includes('bayern')) return CLUBS.BAY;
  return Object.values(CLUBS).find(
    (club) => club.name.toLowerCase() === normalized
  );
}

